def ident(s: str) -> str:
    return s.replace(".", "_")


class Gen:
    def __init__(self, ir: dict):
        self.ir = ir
        self.n = 0
        self.ents = ir["entities"]
        self.enums = ir["enums"]
        self.slots = []  # (entity, attribute, C# type)
        for e, info in sorted(self.ents.items()):
            for a in info["attrs"]:
                self.slots.append((e, a["name"], "bool" if a["type"] == "bool" else "long", a))

    def cstype(self, t: str) -> str:
        return "bool" if t == "bool" else "long"

